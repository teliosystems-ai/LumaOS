#!/usr/bin/env python3
"""Provision externally signed PUBLIC trust inputs before image verity sealing.

This is packaging, not journal publication, trusted time, custody enrollment or
production activation. No private key is accepted or generated by this helper.
"""
import argparse
import base64
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import subprocess

SPKI = bytes.fromhex('302a300506032b6570032100')
MAX_TIME = 4_102_444_800_000
MAX_INTERVAL = 366 * 86_400_000
POLICY_FIELDS = ('schema_version', 'environment', 'domain', 'purpose', 'root_sha256',
                 'not_before_ms', 'expires_ms', 'separated_key_sha256')
TRUST_FIELDS = ('schema_version', 'environment', 'domain', 'purpose', 'policy', 'version',
                'previous_sha256', 'root_sha256', 'not_before_ms', 'expires_ms', 'keys')
KEY_FIELDS = ('id', 'public_key_hex', 'role', 'purpose', 'not_before_ms', 'expires_ms', 'revoked')
ADMISSION_FIELDS = ('schema_version', 'environment', 'domain', 'purpose', 'policy', 'sequence',
                    'trust_version', 'trust_sha256', 'registry_sha256', 'workflow_sha256',
                    'not_before_ms', 'expires_ms', 'signer')
CONTENT = {'skill-trust.json': 32768, 'skill-admission.json': 4096,
           'registry.json': 4096, 'file-to-artifact-v1.json': 65536}
ROOTS = {
    'lab': ('skill-trust-root.pub', 'skill-trust-root-policy.json'),
    'production': ('production-skill-root.pub', 'production-skill-root-policy.json'),
}
LIMITS = {'production-release-root.pub': 4096, **CONTENT,
          **{name: (4096 if name.endswith('.pub') else 32768)
             for pair in ROOTS.values() for name in pair}}
OTHER_KEYS = ('release.pub', 'production-release-root.pub', 'model-catalog.pub',
              'model-pack-root.pub', 'skills/skills.pub',
              'skill-trust-root.pub', 'production-skill-root.pub')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def identity(m):
    return (m.st_dev, m.st_ino, m.st_mode, m.st_uid, m.st_gid, m.st_nlink,
            m.st_size, m.st_mtime_ns, m.st_ctime_ns)


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('duplicate public trust JSON field')
        result[key] = value
    return result


def document(data):
    return json.loads(data, object_pairs_hook=unique,
                      parse_constant=lambda _: (_ for _ in ()).throw(ValueError('nonfinite JSON')))


def closed(value, fields):
    if type(value) is not dict or set(value) != set(fields):
        raise ValueError('public trust JSON closed schema differs')
    return {key: value[key] for key in fields}


def integer(value, minimum=0, maximum=(1 << 63) - 1):
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError('public trust integer is not bounded')
    return value


def hexadecimal(value, size):
    if type(value) is not str or not re.fullmatch('[0-9a-f]{' + str(size * 2) + '}', value):
        raise ValueError('public trust hash/key/signature is not canonical')
    return bytes.fromhex(value)


def identifier(value, alpha=True):
    if type(value) is not str or not re.fullmatch(('[A-Za-z]' if alpha else '[A-Za-z0-9_.-]') +
                                                '[A-Za-z0-9_.-]{0,63}', value):
        raise ValueError('public trust identifier differs')


def validity(value, finite=True):
    start = integer(value['not_before_ms'], 1, MAX_TIME)
    end = integer(value['expires_ms'], 1, MAX_TIME)
    if end <= start or finite and end - start > MAX_INTERVAL:
        raise ValueError('public trust validity is empty or exceeds its bound')


def public_der(pem):
    try:
        text = pem.decode('ascii')
        match = re.fullmatch(r'-----BEGIN PUBLIC KEY-----\r?\n([A-Za-z0-9+/=\r\n]+)'
                             r'-----END PUBLIC KEY-----\r?\n?', text)
        if not match:
            raise ValueError('expected one public-only SPKI PEM block')
        der = base64.b64decode(match[1].replace('\r', '').replace('\n', ''), validate=True)
        if len(der) != 44 or not der.startswith(SPKI) or der[12:] == bytes(32):
            raise ValueError('expected nonzero Ed25519 SPKI public key')
        return der
    except (UnicodeError, ValueError) as error:
        raise ValueError('invalid public Ed25519 key') from error


def compact(value):
    # This order matches the closed Rust skill_trust declarations exactly.
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'), allow_nan=False).encode()


def verify(der, message, signature):
    if len(der) != 44 or not der.startswith(SPKI) or len(signature) != 64 or not message:
        raise ValueError('invalid public signature input')
    executable = os.stat('/usr/bin/openssl', follow_symlinks=True)
    if not stat.S_ISREG(executable.st_mode) or executable.st_uid != 0 or executable.st_mode & 0o022:
        raise ValueError('fixed OpenSSL verifier is not protected')
    descriptors = []
    try:
        for name, data in (('key', der), ('message', message), ('signature', signature)):
            fd = os.memfd_create('luma-public-trust-' + name, os.MFD_ALLOW_SEALING)
            descriptors.append(fd)
            with os.fdopen(os.dup(fd), 'wb') as stream:
                stream.write(data)
            os.lseek(fd, 0, os.SEEK_SET)
            fcntl.fcntl(fd, fcntl.F_ADD_SEALS,
                        fcntl.F_SEAL_WRITE | fcntl.F_SEAL_GROW | fcntl.F_SEAL_SHRINK | fcntl.F_SEAL_SEAL)
        result = subprocess.run(['/usr/bin/openssl', 'pkeyutl', '-verify', '-pubin',
                                 '-keyform', 'DER', '-inkey', '/proc/self/fd/' + str(descriptors[0]),
                                 '-rawin', '-in', '/proc/self/fd/' + str(descriptors[1]),
                                 '-sigfile', '/proc/self/fd/' + str(descriptors[2])],
                                pass_fds=descriptors, stdin=subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                timeout=5, env={'PATH': '/usr/bin', 'LC_ALL': 'C'})
        if result.returncode != 0 or len(result.stdout) + len(result.stderr) > 4096:
            raise ValueError('external public trust signature refuses')
    finally:
        for fd in descriptors:
            os.close(fd)


def inventory(fd):
    names = set()
    with os.scandir(fd) as entries:
        for entry in entries:
            names.add(entry.name)
            if len(names) > 4096:
                raise ValueError('public trust directory inventory exceeds its bound')
    return names


class Directory:
    """Retained, no-follow directory chain and exact bounded member snapshots."""
    def __init__(self, path):
        self.path = Path(os.path.abspath(path))
        self.parents = []
        self.members = {}
        try:
            current = Path('/')
            fd = os.open('/', os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC | os.O_NOFOLLOW)
            self.parents.append((current, fd, identity(os.fstat(fd))))
            for component in self.path.parts[1:]:
                next_fd = os.open(component, os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC | os.O_NOFOLLOW,
                                  dir_fd=fd)
                fd = next_fd
                current = current / component
                self.parents.append((current, fd, identity(os.fstat(fd))))
            self.fd = fd
            self.names = inventory(fd)
            self.recheck()
        except BaseException:
            self.close()
            raise

    def read(self, name, limit):
        if '/' in name or name in ('.', '..'):
            raise ValueError('public input member must be fixed basename')
        fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK, dir_fd=self.fd)
        try:
            before = os.fstat(fd)
            if not stat.S_ISREG(before.st_mode) or before.st_nlink != 1 or not 0 < before.st_size <= limit:
                raise ValueError('public input is not bounded regular single-link bytes')
            data = bytearray()
            while len(data) <= limit:
                chunk = os.read(fd, min(32768, limit + 1 - len(data)))
                if not chunk:
                    break
                data.extend(chunk)
            if len(data) != before.st_size or identity(os.fstat(fd)) != identity(before) \
                    or identity(os.stat(name, dir_fd=self.fd, follow_symlinks=False)) != identity(before):
                raise ValueError('public input changed during bounded snapshot')
            self.members[name] = (fd, identity(before), bytes(data))
            fd = None
            self.recheck()
            return bytes(data)
        finally:
            if fd is not None:
                os.close(fd)

    def recheck(self):
        for path, fd, pin in self.parents:
            # Directory contents may change its mtime only after publication;
            # source snapshots retain the exact inventory independently below.
            if identity(os.fstat(fd))[:5] != pin[:5] or identity(path.lstat())[:5] != pin[:5]:
                raise ValueError('public trust directory namespace changed')
        if hasattr(self, 'names') and inventory(self.fd) != self.names:
            raise ValueError('public trust input inventory changed')
        for name, (fd, pin, data) in self.members.items():
            if identity(os.fstat(fd)) != pin or identity(os.stat(name, dir_fd=self.fd, follow_symlinks=False)) != pin:
                raise ValueError('public trust input member changed')
            if os.pread(fd, len(data) + 1, 0) != data:
                raise ValueError('public trust input snapshot changed')

    def close(self):
        for fd, _, _ in self.members.values():
            os.close(fd)
        self.members = {}
        for _, fd, _ in reversed(self.parents):
            os.close(fd)
        self.parents = []

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()


def validate_graph(data):
    graph = closed(document(data), ('schema_version', 'profile', 'graph_id', 'nodes'))
    if integer(graph['schema_version']) != 1 or graph['profile'] != 'file-to-artifact-v1':
        raise ValueError('unsupported workflow schema/profile')
    identifier(graph['graph_id'], False)
    if type(graph['nodes']) is not list or not 1 <= len(graph['nodes']) <= 64:
        raise ValueError('workflow node bound differs')
    nodes = {}
    contracts = {'file-read': (0, 0, None, 'text'),
                 'deterministic-calculate': (1, 16, 'text', 'report'),
                 'artifact-write': (1, 1, 'report', 'artifact')}
    for candidate in graph['nodes']:
        node = closed(candidate, ('id', 'kind', 'dependencies', 'input_types', 'output_type'))
        identifier(node['id'], False)
        if node['id'] in nodes or type(node['kind']) is not str or node['kind'] not in contracts:
            raise ValueError('duplicate or unsupported workflow node')
        if type(node['dependencies']) is not list or type(node['input_types']) is not list:
            raise ValueError('workflow inputs must be arrays')
        low, high, input_type, output = contracts[node['kind']]
        if not low <= len(node['dependencies']) <= high or len(node['dependencies']) != len(node['input_types']) \
                or node['output_type'] != output or any(value != input_type for value in node['input_types']):
            raise ValueError('workflow type contract differs')
        for dependency in node['dependencies']:
            identifier(dependency, False)
        if len(set(node['dependencies'])) != len(node['dependencies']) or node['id'] in node['dependencies']:
            raise ValueError('workflow dependency is duplicated or self-referencing')
        nodes[node['id']] = node
    for node in nodes.values():
        expected = contracts[node['kind']][2]
        if any(name not in nodes or nodes[name]['output_type'] != expected for name in node['dependencies']):
            raise ValueError('workflow dependency is absent or wrongly typed')
    remaining = {key: set(node['dependencies']) for key, node in nodes.items()}
    while remaining:
        ready = {key for key, dependencies in remaining.items() if not dependencies}
        if not ready:
            raise ValueError('workflow graph is cyclic')
        remaining = {key: dependencies - ready for key, dependencies in remaining.items() if key not in ready}
    sinks = [key for key, node in nodes.items() if node['kind'] == 'artifact-write']
    connected = set()
    while sinks:
        key = sinks.pop()
        if key not in connected:
            connected.add(key)
            sinks.extend(nodes[key]['dependencies'])
    if connected != set(nodes):
        raise ValueError('workflow contains unused nodes')


def validate_skill(values, prohibited):
    signed = closed(document(values['skill-trust.json']), ('trust', 'signature_hex'))
    trust = closed(signed['trust'], TRUST_FIELDS)
    environment = trust['environment']
    if environment not in ROOTS:
        raise ValueError('unsupported skill trust environment')
    root_name, policy_name = ROOTS[environment]
    root = public_der(values[root_name])
    policy = closed(document(values[policy_name]), POLICY_FIELDS)
    validity(policy, False)
    if integer(policy['schema_version']) != 1 or policy['environment'] != environment \
            or policy['domain'] != 'skill-registry' or policy['purpose'] != 'skill-registry' \
            or policy['root_sha256'] != sha(root):
        raise ValueError('skill root policy identity/environment/domain differs')
    separated = policy['separated_key_sha256']
    if type(separated) is not list or len(separated) > 128:
        raise ValueError('skill root separation bound differs')
    for key in separated:
        hexadecimal(key, 32)
    if len(set(separated)) != len(separated) or sha(root) in separated:
        raise ValueError('root policy must uniquely bind its declared historical separated keys')
    prohibited = prohibited | set(separated)
    validity(trust)
    if integer(trust['schema_version']) != 1 or not integer(trust['version'], 1) \
            or trust['domain'] != 'skill-registry' or trust['purpose'] != 'skill-registry' \
            or trust['policy'] != 'closed-file-to-artifact-v1' or trust['root_sha256'] != sha(root) \
            or trust['not_before_ms'] < policy['not_before_ms'] \
            or trust['expires_ms'] > policy['expires_ms'] or sha(root) in prohibited:
        raise ValueError('initial skill trust escapes its independently provisioned root')
    hexadecimal(trust['previous_sha256'], 32)
    if type(trust['keys']) is not list or not 1 <= len(trust['keys']) <= 64:
        raise ValueError('skill delegated key bound differs')
    ids, fingerprints, keys = set(), set(), {}
    for candidate in trust['keys']:
        key = closed(candidate, KEY_FIELDS)
        identifier(key['id'])
        validity(key)
        der = SPKI + hexadecimal(key['public_key_hex'], 32)
        fingerprint = sha(der)
        if der[12:] == bytes(32) or key['id'] in ids or fingerprint in fingerprints \
                or fingerprint == sha(root) or fingerprint in prohibited \
                or key['role'] != 'skill-registry-signer' or key['purpose'] != 'skill-registry' \
                or type(key['revoked']) is not bool or key['not_before_ms'] < trust['not_before_ms'] \
                or key['expires_ms'] > trust['expires_ms']:
            raise ValueError('skill leaf identity/domain/separation/validity differs')
        ids.add(key['id']); fingerprints.add(fingerprint); keys[key['id']] = key
    trust['keys'] = list(keys.values())
    signed = {'trust': trust, 'signature_hex': signed['signature_hex']}
    verify(root, compact(trust), hexadecimal(signed['signature_hex'], 64))
    admission = closed(document(values['skill-admission.json']), ('metadata', 'signature_hex'))
    metadata = closed(admission['metadata'], ADMISSION_FIELDS)
    validity(metadata)
    signer = keys.get(metadata['signer'])
    if not signer or signer['revoked'] or integer(metadata['schema_version']) != 1 \
            or metadata['environment'] != environment or metadata['domain'] != 'skill-registry' \
            or metadata['purpose'] != 'skill-registry' or metadata['policy'] != 'closed-file-to-artifact-v1' \
            or not integer(metadata['sequence'], 1) or metadata['trust_version'] != trust['version'] \
            or type(metadata['trust_version']) is not int or metadata['trust_sha256'] != sha(compact(signed)) \
            or metadata['registry_sha256'] != sha(values['registry.json']) \
            or metadata['workflow_sha256'] != sha(values['file-to-artifact-v1.json']) \
            or metadata['not_before_ms'] < signer['not_before_ms'] or metadata['expires_ms'] > signer['expires_ms']:
        raise ValueError('initial registry admission does not bind exact signed trust and immutable contents')
    verify(SPKI + bytes.fromhex(signer['public_key_hex']), compact(metadata), hexadecimal(admission['signature_hex'], 64))
    validate_graph(values['file-to-artifact-v1.json'])
    registry = closed(document(values['registry.json']),
                      ('schema_version', 'environment', 'profile', 'workflow_sha256', 'skills'))
    expected = [{'id': 'file-read', 'input_types': [], 'output_type': 'text'},
                {'id': 'deterministic-calculate', 'input_types': ['text'], 'output_type': 'report'},
                {'id': 'artifact-write', 'input_types': ['report'], 'output_type': 'artifact'}]
    if integer(registry['schema_version']) != 2 or registry['environment'] != environment \
            or registry['profile'] != 'file-to-artifact-v1' \
            or registry['workflow_sha256'] != sha(values['file-to-artifact-v1.json']) \
            or type(registry['skills']) is not list or registry['skills'] != expected:
        raise ValueError('unsupported or wrongly bound governed schema-two registry')
    return environment


def publish(root, relative, data):
    destination = root / relative
    # Create only the fixed image subdirectories beneath pinned, nonsymlink
    # parents. Never follow a replaced parent while creating image contents.
    with Directory(root) as base:
        current = base.fd
        opened = []
        try:
            for component in Path(relative).parts[:-1]:
                try:
                    os.mkdir(component, mode=0o755, dir_fd=current)
                except FileExistsError:
                    pass
                fd = os.open(component, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC,
                             dir_fd=current)
                opened.append(fd)
                m = os.fstat(fd)
                if m.st_uid != 0 or m.st_mode & 0o022:
                    raise ValueError('image public-input directory is not protected')
                current = fd
            for path, fd, pin in base.parents:
                if identity(os.fstat(fd))[:5] != pin[:5] or identity(path.lstat())[:5] != pin[:5]:
                    raise ValueError('image root changed during fixed-directory creation')
        finally:
            for fd in reversed(opened):
                os.close(fd)
    with Directory(destination.parent) as parent:
        before = None
        if destination.name in parent.names:
            before = destination.lstat()
            if not stat.S_ISREG(before.st_mode) or before.st_uid != 0 or before.st_nlink != 1 or before.st_mode & 0o022:
                raise ValueError('existing image public member is not protected')
        staging = '.public-trust-' + os.urandom(16).hex()
        fd = os.open(staging, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
                     0o644, dir_fd=parent.fd)
        try:
            with os.fdopen(os.dup(fd), 'wb') as stream:
                stream.write(data); stream.flush(); os.fsync(stream.fileno())
            os.fchmod(fd, 0o644)
            os.fsync(fd)
            retained = identity(os.fstat(fd))
            if os.pread(fd, len(data) + 1, 0) != data:
                raise ValueError('public staged bytes differ')
            parent.names.add(staging)
            parent.recheck()
            if identity(os.stat(staging, dir_fd=parent.fd, follow_symlinks=False)) != retained:
                raise ValueError('public staging member changed')
            if before is not None and identity(destination.lstat()) != identity(before):
                raise ValueError('image destination changed during publication')
            os.rename(staging, destination.name, src_dir_fd=parent.fd, dst_dir_fd=parent.fd)
            parent.names.discard(staging); parent.names.add(destination.name)
            os.fsync(parent.fd)
            parent.recheck()
            after = identity(os.fstat(fd))
            if after[:-1] != retained[:-1] or identity(destination.lstat()) != after \
                    or os.pread(fd, len(data) + 1, 0) != data:
                raise ValueError('public image publication readback differs')
        finally:
            os.close(fd)


def provision(root, public_inputs=None):
    if public_inputs is None:
        return {'schema_version': 1, 'provided': False, 'skill_registry': False, 'activated': False}
    root = Path(root)
    if root.is_symlink() or not root.is_dir():
        raise ValueError('image root must be an existing nonsymlink directory')
    with Directory(public_inputs) as source:
        if not source.names or not source.names <= set(LIMITS):
            raise ValueError('public trust input directory is empty or contains unknown/private members')
        values = {name: source.read(name, LIMITS[name]) for name in sorted(source.names)}
        skill_names = source.names - {'production-release-root.pub'}
        environment = None
        if skill_names:
            if not set(CONTENT) <= skill_names:
                raise ValueError('partial externally signed skill group refuses')
            signed = closed(document(values['skill-trust.json']), ('trust', 'signature_hex'))
            environment = signed['trust'].get('environment') if type(signed['trust']) is dict else None
            if environment not in ROOTS or skill_names != set(CONTENT) | set(ROOTS[environment]):
                raise ValueError('mixed or partial skill root/content group refuses')
            with Directory(root / 'usr/share/luma-os') as image:
                identity_value = closed(document(image.read('release-identity.json', 4096)),
                                        ('schema_version', 'release', 'sequence', 'environment',
                                         'architecture', 'ubuntu', 'edition'))
                identifier(identity_value['release'])
                integer(identity_value['sequence'], 1)
                if integer(identity_value['schema_version']) != 1 \
                        or identity_value['environment'] != environment \
                        or identity_value['architecture'] != 'amd64' \
                        or identity_value['ubuntu'] != '24.04' \
                        or identity_value['edition'] not in ('headless', 'desktop'):
                    raise ValueError('governed registry environment does not match the closed image identity')
                image.recheck()
        prohibited = set()
        for relative in OTHER_KEYS:
            path = root / 'usr/share/luma-os' / relative
            if path.exists() or path.is_symlink():
                with Directory(path.parent) as existing:
                    prohibited.add(sha(public_der(existing.read(path.name, 4096))))
        if 'production-release-root.pub' in values:
            production = sha(public_der(values['production-release-root.pub']))
            if production in prohibited:
                raise ValueError('production release root reuses a packaged domain key')
            prohibited.add(production)
        if environment:
            validate_skill(values, prohibited)
        source.recheck()
        outputs = {}
        if 'production-release-root.pub' in values:
            outputs['usr/share/luma-os/production-release-root.pub'] = values['production-release-root.pub']
        if environment:
            for name in ROOTS[environment]:
                outputs['usr/share/luma-os/' + name] = values[name]
            for source_name, target_name in (('skill-trust.json', 'skills/initial-trust.json'),
                                             ('skill-admission.json', 'skills/initial-admission.json'),
                                             ('registry.json', 'skills/registry.json'),
                                             ('file-to-artifact-v1.json', 'workflows/file-to-artifact-v1.json')):
                outputs['usr/share/luma-os/' + target_name] = values[source_name]
        for relative, data in outputs.items():
            source.recheck()
            publish(root, relative, data)
            source.recheck()
        return {'schema_version': 1, 'provided': True, 'skill_registry': bool(environment),
                'environment': environment, 'activated': False,
                'files': {relative: sha(data) for relative, data in sorted(outputs.items())}}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--public-inputs', type=Path)
    arguments = parser.parse_args()
    print(json.dumps(provision(arguments.root, arguments.public_inputs), sort_keys=True))
