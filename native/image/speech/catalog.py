"""Exact auxiliary-ASR signed-data projection, not text model compatibility."""
import hashlib
try:
    from . import model_layout as layout
except ImportError:
    import importlib.util
    from pathlib import Path
    spec = importlib.util.spec_from_file_location('luma_speech_model_layout', Path(__file__).with_name('model_layout.py'))
    layout = importlib.util.module_from_spec(spec); spec.loader.exec_module(layout)

PROFILE = 'whisper-tiny-multilingual-f16-cpu-v1'
MEMORY = 512*1024*1024
TUPLE = {'os_family': 'Linux', 'architecture': 'amd64', 'backend': 'whisper.cpp',
         'backend_version': 'v1.9.5-luma-asr-v1', 'device': 'cpu'}
LICENSE_SHA256 = 'b5d65a59060e68c4ff940e1eddfa6f94b2d68fdf58ed7f4dd57721c997e35e9d'


def sha(value):
    return hashlib.sha256(value).hexdigest()


def validate(p, m):
    """Validate the same closed adapter as model/speech.rs before provisioning.

    Full public signatures, auxiliary bytes/inventory and actual certificate
    signatures remain mandatory at the common provisioning boundary.
    """
    runtime = sha(layout.canonical(TUPLE))
    weights = [b for b in m['blobs'] if b['role'] == 'model']
    licenses = [b for b in m['blobs'] if b['role'] == 'license']
    sidecars = [(role, layout.canonical(value)) for role, value in
                [('tokenizer', layout.tokenizer()), ('template', layout.policy())]]
    for role, content in sidecars:
        blobs = [b for b in m['blobs'] if b['role'] == role]
        if len(blobs) != 1 or blobs[0]['size_bytes'] != len(content) or blobs[0]['sha256'] != sha(content):
            raise ValueError('auxiliary ASR embedded-tokenizer/decoding descriptor differs')
    size = sum(b['size_bytes'] for b in m['blobs'])
    memory = lambda values: values == [{'domain': 'host', 'bytes': MEMORY}]
    model = m['model']
    installs = m['installation_profiles']
    if p['profile_id'] != PROFILE or p['kind'] != 'model' or p['execution_mode'] != 'cpu' or p['runtime_tuple_sha256'] != runtime or m['runtime_tuples'] != [TUPLE] or len(installs) != 1 or len(m['blobs']) != 4 or len(weights) != 1 or weights[0]['sha256'] != layout.MODEL_SHA256 or weights[0]['size_bytes'] != layout.MODEL_BYTES or weights[0].get('shard_index') != 0 or len(licenses) != 1 or licenses[0]['sha256'] != LICENSE_SHA256 or licenses[0]['size_bytes'] != 1063 or model['architecture'] != 'whisper-tiny-multilingual' or model['total_parameters'] != layout.PARAMETERS or model['active_parameters_min'] != layout.PARAMETERS or model['active_parameters_max'] != layout.PARAMETERS or model['quantization'] != 'mixed-F16-F32' or model['source'] != layout.MODEL_URL or model['required_features'] != ['automatic-speech-recognition', 'offline', 'speech-transcription'] or m['context']['maximum_tokens'] != 448 or m['license']['identifier'] != 'MIT' or m['license']['evaluation'] != 'approved' or m['license']['redistribution'] != 'approved' or p['parameter_total'] != layout.PARAMETERS or p['parameter_active_min'] != layout.PARAMETERS or p['parameter_active_max'] != layout.PARAMETERS or p['model_pack_manifest_sha256'] != sha(layout.canonical(m)) or p['context_tokens'] != 448 or p['minimum_host_ram_bytes'] < 2*1024**3 or p['minimum_accelerator_memory_bytes'] != 0 or p['install_bytes'] != size or p['storage_peak_bytes'] < size+256*1024**2 or not memory(p['load_reservations']) or not memory(p['serve_reservations']) or p['remote_fallback'] is not False:
        raise ValueError('catalog/pack changes or understates the exact ASR auxiliary tuple')
    install = installs[0]
    if install['profile_id'] != PROFILE or install['runtime_tuple_sha256'] != runtime or install['execution_mode'] != 'cpu' or install['minimum_accelerator_memory_bytes'] != 0 or install['minimum_host_ram_bytes'] > p['minimum_host_ram_bytes'] or install['minimum_model_storage_bytes'] > p['storage_peak_bytes'] or install['maximum_context_tokens'] != 448:
        raise ValueError('ASR installation tuple differs from actual initial decoder profile')
    return runtime


def proposal(weights, license_bytes, signer_key_id, *, lab_candidate=False, software_test_report_sha256=None):
    """Unsigned, unavailable data proposal derived from actual pinned weights.

    The default never infers availability. An explicit lab-candidate request
    names an independently retained actual software report and proposes the
    final immutable capability declarations for the existing signing workflow.
    These declarations require real lab certification inputs or separately
    delivered exact-image/machine production certificates; no signature,
    certificate, admission or runtime authority is generated by this function.
    """
    descriptor = layout.inspect(weights)
    report = software_test_report_sha256
    if type(lab_candidate) is not bool or (lab_candidate and (not isinstance(report, str) or len(report) != 64 or any(c not in '0123456789abcdef' for c in report) or report == '0'*64)) or (not lab_candidate and report is not None):
        raise ValueError('explicit lab-candidate choice and exact actual software-report digest required')
    if not isinstance(license_bytes, bytes) or len(license_bytes) != 1063 or sha(license_bytes) != LICENSE_SHA256 or not isinstance(signer_key_id, str) or not 1 <= len(signer_key_id) <= 256 or not signer_key_id.isascii() or any(ord(c) < 33 or ord(c) > 126 for c in signer_key_id):
        raise ValueError('exact original MIT model notice and explicit signing-key identity required')
    sidecars = [('tokenizer', layout.canonical(layout.tokenizer())),
                ('template', layout.canonical(layout.policy())), ('license', license_bytes)]
    blobs = [{'role': 'model', 'path': 'blobs/sha256/'+layout.MODEL_SHA256,
              'sha256': layout.MODEL_SHA256, 'size_bytes': layout.MODEL_BYTES, 'shard_index': 0}]
    files = {}
    for role, content in sidecars:
        digest = sha(content)
        name = 'licenses/WHISPER-MIT.txt' if role == 'license' else 'blobs/sha256/'+digest
        blobs.append({'role': role, 'path': name, 'sha256': digest, 'size_bytes': len(content)})
        files[name] = content
    size = sum(b['size_bytes'] for b in blobs)
    peak = size+256*1024**2
    runtime = sha(layout.canonical(TUPLE))
    manifest = {'schema_version': 2, 'canonicalization': 'RFC8785-ASCII-v1', 'signature_algorithm': 'Ed25519',
        'pack_id': PROFILE, 'pack_version': '1.0.0', 'model': {'architecture': 'whisper-tiny-multilingual',
            'identity': 'OpenAI Whisper tiny multilingual GGML', 'parameter_class': '37760640-stored-scalars',
            'total_parameters': layout.PARAMETERS, 'active_parameters_min': layout.PARAMETERS,
            'active_parameters_max': layout.PARAMETERS, 'quantization': 'mixed-F16-F32',
            'required_features': ['automatic-speech-recognition', 'offline', 'speech-transcription'], 'source': layout.MODEL_URL},
        'context': {'maximum_tokens': 448, 'template_sha256': blobs[2]['sha256']}, 'blobs': blobs,
        'runtime_tuples': [TUPLE], 'installation_profiles': [{'profile_id': PROFILE,
            'runtime_tuple_sha256': runtime, 'execution_mode': 'cpu', 'minimum_host_ram_bytes': 2*1024**3,
            'minimum_accelerator_memory_bytes': 0, 'minimum_model_storage_bytes': peak, 'maximum_context_tokens': 448}],
        'license': {'identifier': 'MIT', 'evaluation': 'approved', 'redistribution': 'approved', 'files': [blobs[3]['path']]},
        'network_default': 'deny', 'signer_key_id': signer_key_id}
    profile = {'availability': 'unavailable', 'certification_state': 'not-certified', 'context_tokens': 448,
        'development_state': 'untested', 'execution_mode': 'cpu', 'install_bytes': size, 'kind': 'model',
        'load_reservations': [{'domain': 'host', 'bytes': MEMORY}], 'minimum_accelerator_memory_bytes': 0,
        'minimum_host_ram_bytes': 2*1024**3, 'model_pack_manifest_sha256': sha(layout.canonical(manifest)),
        'parameter_active_max': layout.PARAMETERS, 'parameter_active_min': layout.PARAMETERS,
        'parameter_total': layout.PARAMETERS, 'profile_id': PROFILE, 'remote_fallback': False,
        'runtime_tuple_sha256': runtime, 'serve_reservations': [{'domain': 'host', 'bytes': MEMORY}],
        'storage_peak_bytes': peak, 'verification_state': 'unverified'}
    if lab_candidate:
        profile.update(availability='available', verification_state='verified',
            development_state='development-tested', certification_state='interactive-certified')
    validate(profile, manifest)
    return {'manifest': manifest, 'profile': profile, 'files': files, 'layout': descriptor,
        'proposal_authority': {'unsigned': True, 'lab_candidate_explicitly_requested': lab_candidate,
            'software_test_report_sha256': report, 'certifications_generated': False,
            'runtime_admitted': False, 'existing_model_custody_approval_required': True,
            'required_certifications_before_candidate_admission': ['execution', 'interactive'] if lab_candidate else [],
            'production_certifications_require_actual_image_and_machine': True}}
